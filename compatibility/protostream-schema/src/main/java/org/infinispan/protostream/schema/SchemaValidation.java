package org.infinispan.protostream.schema;

import java.util.Locale;

/**
 * Validation errors from the upstream schema builder.
 *
 * @author 芋道源码
 */
final class SchemaValidation {
   private SchemaValidation() {}

   static IllegalArgumentException reservedName(String name, String owner) {
      return new IllegalArgumentException(String.format(Locale.ROOT, "Name '%s' is reserved on '%s'", name, owner));
   }

   static IllegalArgumentException reservedNumber(int number, String name, String owner) {
      return new IllegalArgumentException(String.format(Locale.ROOT, "Number %d used by '%s' is reserved on '%s'", number, name, owner));
   }

   static IllegalArgumentException invalidFieldNumber(int number, String name) {
      return new IllegalArgumentException(String.format(Locale.ROOT,
            "Number %d used by field '%s' violates the Protocol Buffer specification", number, name));
   }

   static IllegalArgumentException cannotMixAutoGeneratedNumbers(String name) {
      return new IllegalArgumentException("Type '" + name + "' may not mix auto-generated field/enum numbers with explicit and/or reserved numbers");
   }

   static IllegalStateException missingDefaultEnumValue(String name) {
      return new IllegalStateException("Enum '" + name + "' must have a default enum value (with number = 0)");
   }
}
